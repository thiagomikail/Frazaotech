export type Params = Record<string, string | number>;

export function translate(lang: Lang, key: TKey, params?: Params): string {
  let s = (lang === 'pt' ? pt : en)[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function guessLang(): Lang {
  try {
    const saved = window.localStorage.getItem('petriplc:lang');
    if (saved === 'pt' || saved === 'en') return saved;
  } catch {
    // Private mode: fall back to the browser language.
  }
  return navigator.language?.toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

export const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({
  lang: 'pt',
  setLang: () => {},
});

export function useT() {
  const { lang } = useContext(LangContext);
  return (key: TKey, params?: Params) => translate(lang, key, params);
}

export const useLang = () => useContext(LangContext);
